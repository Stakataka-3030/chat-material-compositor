import { newProject, type Appearance } from "./model.js";
import {
  scopeDefaults,
  extractAppearance,
  type ConfigScope,
} from "./appearance-config.js";
import type { PhoneUI } from "./phone-ui.js";
export interface AppearancePreset {
  id: string;
  name: string;
  scope: Exclude<ConfigScope, "all">;
  appearance: Partial<Appearance>;
}
function preset(
  id: string,
  name: string,
  scope: AppearancePreset["scope"],
  ui: Partial<PhoneUI>,
  appearance: Partial<Appearance> = {},
): AppearancePreset {
  const base = extractAppearance(newProject().appearance, scope);
  // Content, time, battery and the output transform are not changed by choosing a style.
  for (const key of ["statusTime", "battery", "charging"] as const)
    delete base[key];
  return {
    id,
    name,
    scope,
    appearance: {
      ...base,
      ...appearance,
      ui: { ...scopeDefaults(scope), ...ui },
    },
  };
}
